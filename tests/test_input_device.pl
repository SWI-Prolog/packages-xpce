:- module(test_input_device, [test_input_device/0]).

/** <module> Input devices of events

Each event refers to the input_device that generated it.  Events that
do not specify a device get @keyboard_device if they are keyboard
events and the device of the last pointer event otherwise.

An event delegates to its <-detail, so the methods of the detail are
available on the event.

Each pointer device has its own defaults and multiclick detection, so
interleaved events of the mouse and a pen do not disturb each other.

Run with:

    swipl -g test_input_device -t halt \
          packages/xpce/tests/test_input_device.pl
*/

:- use_module(library(pce)).
:- use_module(library(plunit)).

setup_headless :-
    set_prolog_flag('SDL_VIDEODRIVER', dummy).
:- initialization(setup_headless, now).

test_input_device :-
    run_tests([ input_device,
                event_detail,
                pointer_state
              ]).

%!  event(+Id, +Window, ?Device, -Event) is det.
%
%   Create an event at (10,10) of Window, generated by Device.  If
%   Device is unbound, the event uses the default device.

event(Id, W, Device, E) :-
    (   var(Device)
    ->  new(E, event(Id, W, 10, 10))
    ;   new(E, event(Id, W, 10, 10, @default, @default, Device))
    ).

device(E, D) :-
    get(E, device, D).

:- begin_tests(input_device).

test(predefined, [MK-MI-KK == mouse-0-keyboard]) :-
    get(@mouse_device, kind, MK),
    get(@mouse_device, id, MI),
    get(@keyboard_device, kind, KK).
test(registry, true) :-
    get(@display, input_devices, Chain),
    send(Chain, member, @mouse_device),
    send(Chain, member, @keyboard_device).
test(mouse, D == @mouse_device) :-
    new(P, picture),
    event(ms_left_down, P, @mouse_device, E),
    device(E, D).
test(character, D == @keyboard_device) :-
    new(P, picture),
    event(0'a, P, _, E),
    device(E, D).
test(named_key, D == @keyboard_device) :-
    new(P, picture),
    event(cursor_up, P, _, E),
    device(E, D).
test(last_pointer, [D1-D2 == Pen-Pen]) :-
    new(P, picture),
    new(Pen, input_device(pen, 7, 'Test pen')),
    event(ms_left_down, P, Pen, _),
    event(loc_move, P, _, E1),
    event(0'a, P, _, _),                % does not change the pointer
    event(loc_move, P, _, E2),
    device(E1, D1),
    device(E2, D2),
    event(loc_move, P, @mouse_device, _).
test(no_detail, Detail == @nil) :-
    new(P, picture),
    event(loc_move, P, @mouse_device, E),
    get(E, detail, Detail).
test(clone_shares_device, D == Pen) :-
    new(P, picture),
    new(Pen, input_device(pen, 8)),
    event(ms_left_down, P, Pen, E),
    get(E, clone, E2),
    device(E2, D),
    event(loc_move, P, @mouse_device, _).
test(keyboard_class, true) :-
    send(@keyboard_device, instance_of, keyboard).
test(key_names, Vs == [@off, @off, @off, @off, @off]) :-
    findall(V, ( member(K, [cursor_left, a, space, 'Left Shift', f5]),
                 get(@keyboard_device, key_down, K, V)
               ), Vs).                  % no key is held during the test
test(unknown_key, fail) :-
    get(@keyboard_device, key_down, no_such_key, _).
test(device_name, [N == pen]) :-
    new(Pen, input_device(pen)),
    get(Pen, name, N).

:- end_tests(input_device).

%!  drop_event(+Id, +Detail, -Event) is det.
%
%   Create a drop event Id whose <-detail is Detail.

drop_event(Id, Detail, E) :-
    new(P, picture),
    event(Id, P, @mouse_device, E),
    send(E, slot, detail, Detail).

:- begin_tests(event_detail).

test(drop_file_path, Path == '/tmp/dropped.txt') :-
    drop_event(drop_file, drop_data(path := '/tmp/dropped.txt'), E),
    get(E, path, Path).
test(drop_file_no_text, fail) :-
    drop_event(drop_file, drop_data(path := '/tmp/dropped.txt'), E),
    get(E, text, _).
test(drop_text, Text == "hello") :-
    drop_event(drop_text, drop_data(text := string(hello)), E),
    get(E, text, Str),
    get(Str, value, Value),
    atom_string(Value, Text).
test(source, [Source == nautilus]) :-
    drop_event(drop_file, drop_data(path := x, source := nautilus), E),
    get(E, source, Source).
test(no_source, fail) :-
    drop_event(drop_file, drop_data(path := x), E),
    get(E, source, _).
test(event_methods_first, [X-Id == 10-drop_file]) :-
    drop_event(drop_file, drop_data(path := x), E),
    get(E, x, X),
    get(E, id, Id).
test(wheel_data, [DX-DY-F == 0.25-(-1.5)-(@off)]) :-
    drop_event(wheel, wheel_data(0.25, -1.5), E),
    get(E, dx, DX),
    get(E, dy, DY),
    get(E, flipped, F).
test(wheel_flipped, F == @on) :-
    drop_event(wheel, wheel_data(0, 1, @on), E),
    get(E, flipped, F).

:- end_tests(event_detail).

%!  at(+Id, +Window, +Device, +X, +Time, -Event) is det.
%
%   Create an event at (X,X) of Window at Time, generated by Device.

at(Id, W, Device, X, T, E) :-
    new(E, event(Id, W, X, X, @default, T, Device)).

:- begin_tests(pointer_state).

test(interleaved_double_click, [C1-C2 == single-double]) :-
    new(P, picture),
    new(Pen, input_device(pen, 21)),
    at(ms_left_down, P, @mouse_device, 10, 10000, E1),
    at(ms_left_up,   P, @mouse_device, 10, 10010, _),
    at(ms_left_down, P, Pen,          200, 10050, _),
    at(ms_left_up,   P, Pen,          200, 10060, _),
    at(ms_left_down, P, @mouse_device, 10, 10100, E2),
    at(ms_left_up,   P, @mouse_device, 10, 10110, _),
    get(E1, multiclick, C1),
    get(E2, multiclick, C2),
    send(Pen, free).
test(own_default_position, [X == 10]) :-
    new(P, picture),
    new(Pen, input_device(pen, 22)),
    at(loc_move, P, @mouse_device, 10, @default, _),
    at(loc_move, P, Pen, 300, @default, _),
    new(E, event(loc_move, P, @default, @default,
                 @default, @default, @mouse_device)),
    get(E, x, P, X),
    send(Pen, free).
test(keyboard_follows_pointer, [X-D == 300-(@keyboard_device)]) :-
    new(P, picture),
    new(Pen, input_device(pen, 23)),
    at(loc_move, P, @mouse_device, 10, @default, _),
    at(loc_move, P, Pen, 300, @default, _),
    new(E, event(0'a, P)),
    get(E, x, P, X),
    get(E, device, D),
    at(loc_move, P, @mouse_device, 10, @default, _),
    send(Pen, free).
test(click_displacement, [D == 0]) :-
    new(P, picture),
    new(Pen, input_device(pen, 24)),
    at(ms_left_down, P, @mouse_device, 10, 20000, _),
    at(ms_left_down, P, Pen,          200, 20010, _),
    at(ms_left_up,   P, Pen,          200, 20020, _),
    at(ms_left_up,   P, @mouse_device, 10, 20030, Up),
    get(Up, click_displacement, D),
    send(Pen, free).
test(freed_device, [D == @mouse_device]) :-
    new(P, picture),
    new(Pen, input_device(pen, 25)),
    at(loc_move, P, Pen, 300, @default, _),
    send(Pen, free),
    new(E, event(loc_move, P)),
    get(E, device, D).

:- end_tests(pointer_state).
