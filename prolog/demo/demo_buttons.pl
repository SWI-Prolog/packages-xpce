:- module(demo_buttons, []).
:- use_module(library(pce)).

/** <module> Buttons shared by the demos

Class state_button is a button whose label changes with the state, e.g.,
"Record" and "Stop".  It is wide enough for both, so the buttons to its
right do not move when the label changes.
*/

:- pce_begin_class(state_button, button,
                   "Button with a label that changes").

class_variable(size, size, size(125, 20)).

:- pce_end_class(state_button).
