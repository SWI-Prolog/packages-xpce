%!  key_pose(?T, ?HipHeight, ?Pitch, ?Thigh, ?Shin, ?Foot, ?Tail, ?Arm)
%
%   Key poses of the hop.  T is the moment in the hop (0..1).  Angles
%   are in degrees.  Pitch is the angle of the body axis above
%   horizontal.  Thigh, Shin and Foot are the direction of the segment:
%   0 points forward (right), 90 down and 180 backward.  Tail is the
%   direction of the tail base, 180 is straight back.  HipHeight is not
%   used: the height follows from the feet.

key_pose(0.00, 38, 30,  25, 125,  12, 205, 110).  % landing: legs forward
key_pose(0.17, 30, 22,   0, 150,   4, 210, 120).  % deep crouch
key_pose(0.34, 56, 45, 115, 145, 115, 175,  95).  % take-off: legs back
key_pose(0.55, 60, 42, 125, 145, 150, 178,  80).  % flight: legs trailing
key_pose(0.78, 58, 36,  70, 110,  40, 185,  95).  % legs swing forward
key_pose(0.92, 46, 32,  35, 115,  10, 195, 105).  % reaching for the ground
key_pose(1.00, 38, 30,  25, 125,  12, 205, 110).

