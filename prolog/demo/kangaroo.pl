%!  capsule(+Points, +Widths, -Shape) is det.
%
%   A tapered stroke through Points with the given half widths, as a
%   closed smooth shape.

capsule(Points, Widths, smooth(Poly)) :-
    length(Points, Len),
    numlist(1, Len, Is),
    maplist(side_points(Points), Is, Widths, Left, Right),
    reverse(Right, RRight),
    append(Left, RRight, Poly).

side_points(Points, I, W, LX-LY, RX-RY) :-
    nth1(I, Points, X-Y),
    length(Points, Len),
    (   I == 1
    ->  nth1(2, Points, X2-Y2), DX is X2-X, DY is Y2-Y
    ;   I == Len
    ->  Ip is I-1, nth1(Ip, Points, X0-Y0), DX is X-X0, DY is Y-Y0
    ;   Ip is I-1, In is I+1,
        nth1(Ip, Points, X0-Y0), nth1(In, Points, X2-Y2),
        DX is X2-X0, DY is Y2-Y0
    ),
    N0 is sqrt(DX*DX+DY*DY),
    ( N0 =:= 0 -> N = 1 ; N = N0 ),
    NX is -DY/N, NY is DX/N,
    LX is X+NX*W, LY is Y+NY*W,
    RX is X-NX*W, RY is Y-NY*W.

%!  catmull(+Poly, -PathData) is det.
%
%   PathData is SVG path data for a closed Catmull-Rom spline through
%   the points of Poly.

catmull(Poly, Data) :-
    length(Poly, N),
    Poly = [X0-Y0|_],
    format(string(Start), 'M~1f,~1f', [X0, Y0]),
    Last is N-1,
    numlist(0, Last, Is),
    maplist(catmull_segment(Poly, N), Is, Segments),
    append([Start|Segments], [" Z"], Parts),
    atomic_list_concat(Parts, Data).

catmull_segment(Poly, N, I, Seg) :-
    I0 is (I-1+N) mod N, I2 is (I+1) mod N, I3 is (I+2) mod N,
    nth0(I0, Poly, X0-Y0), nth0(I, Poly, X1-Y1),
    nth0(I2, Poly, X2-Y2), nth0(I3, Poly, X3-Y3),
    C1X is X1 + (X2-X0)/6, C1Y is Y1 + (Y2-Y0)/6,
    C2X is X2 - (X3-X1)/6, C2Y is Y2 - (Y3-Y1)/6,
    format(string(Seg), ' C~1f,~1f ~1f,~1f ~1f,~1f',
           [C1X, C1Y, C2X, C2Y, X2, Y2]).

%!  svg_shape(+Shape, +Fill, +Stroke, -SVG) is det.
%
%   SVG element for Shape.  Stroke is `none` or stroke(Colour, Width).

svg_shape(Shape, Fill, Stroke, SVG) :-
    shape_style(Fill, Stroke, Style),
    svg_element(Shape, Style, SVG).

shape_style(Fill, none, Style) :-
    !,
    format(string(Style), 'fill="~w"', [Fill]).
shape_style(Fill, stroke(Colour, Width), Style) :-
    format(string(Style),
           'fill="~w" stroke="~w" stroke-width="~1f" stroke-linejoin="round"',
           [Fill, Colour, Width]).

svg_element(ellipse(CX, CY, RX, RY, A), Style, SVG) :-
    format(string(SVG),
           '<ellipse cx="~1f" cy="~1f" rx="~1f" ry="~1f" \c
            transform="rotate(~1f ~1f ~1f)" ~w/>',
           [CX, CY, RX, RY, A, CX, CY, Style]).
svg_element(smooth(Poly), Style, SVG) :-
    catmull(Poly, Data),
    format(string(SVG), '<path d="~w" ~w/>', [Data, Style]).

