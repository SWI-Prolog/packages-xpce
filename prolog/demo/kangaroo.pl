%!  pose(+T, -Pose:list) is det.
%
%   Interpolate the key poses at moment T, easing in and out of each
%   key pose.

pose(T, Pose) :-
    findall(K-P, key_pose_list(K, P), Keys),
    append(_, [T0-P0, T1-P1|_], Keys),
    T0 =< T, T =< T1,
    !,
    ease((T-T0)/(T1-T0), F),
    maplist(lerp(F), P0, P1, Pose).

key_pose_list(T, [HH,P,Th,Sh,Ft,Tl,Ar]) :-
    key_pose(T, HH, P, Th, Sh, Ft, Tl, Ar).

lerp(F, A, B, V) :-
    V is A + (B-A)*F.

ease(F, V) :-
    V is 0.5 - 0.5*cos(pi*F).

%!  pt(+P0, +Angle, +Length, -P) is det.
%
%   P is Length from P0 in direction Angle (degrees).

pt(X0-Y0, Ang, Len, X-Y) :-
    A is Ang*(pi/180),
    X is X0 + cos(A)*Len,
    Y is Y0 + sin(A)*Len.

