%!  kangaroo_shapes(+T, -Near, -Far, -Details, -Low, -ToeX) is det.
%
%   The shapes of the kangaroo at moment T, with the hip at (0,0).
%   Near and Far are the shapes of the near side and the far limbs.
%   Details is a list of Kind-Shape.  Low is the y of the lowest point
%   of the feet and ToeX the x of the toe, both scaled.

kangaroo_shapes(T, Near, Far, Details, Low, ToeX) :-
    pose(T, [_HipH, Pitch, AThigh, AShin, AFoot, ATail, AArm]),
    Hip = 0.0-0.0,
    BodyDir is -Pitch,                  % SVG: negative is up
    pt(Hip, BodyDir, 46, Shoulder),
    NeckDir is BodyDir-35,
    pt(Shoulder, NeckDir, 16, Neck),
    HeadDir is -10-Pitch*0.3,
    pt(Neck, HeadDir, 12, Head),
    % leg
    pt(Hip, AThigh, 26, Knee),
    pt(Knee, AShin, 30, Ankle),
    pt(Ankle, AFoot, 34, Toe),
    % tail
    TailDir is BodyDir+180,
    pt(Hip, TailDir, 10, TailBase),
    A1 is ATail-10, pt(TailBase, A1, 30, T1),
    A2 is ATail+5,  pt(T1, A2, 30, T2),
    A3 is ATail+18, pt(T2, A3, 24, T3),
    % arm from the chest
    ChestDir is BodyDir-8,
    pt(Hip, ChestDir, 36, Chest),
    pt(Chest, AArm, 12, Elbow),
    PawDir is AArm-60,
    pt(Elbow, PawDir, 10, Paw),
    % far limbs, slightly offset
    shift(Knee, -4, -2, FK), shift(Ankle, -4, -2, FA), shift(Toe, -4, -2, FT),
    capsule([FK, FA, FT], [6, 4, 3], FarLeg),
    pt(Chest, -60, 3, FC), pt(Elbow, -60, 3, FE), pt(Paw, -60, 3, FP),
    capsule([FC, FE, FP], [3.2, 2.6, 2.2], FarArm),
    Far = [FarLeg, FarArm],
    % tail and torso
    capsule([TailBase, T1, T2, T3], [12, 8, 5, 2], Tail),
    pt(Hip, BodyDir, 20, Mid),
    ellipse(Hip, 20, 18, BodyDir, Rump),
    ellipse(Mid, 32, 20, BodyDir, Torso),
    ellipse(Chest, 16, 14, BodyDir, ChestE),
    capsule([Shoulder, Neck, Head], [10, 7, 6], NeckS),
    % head with snout
    SnoutDir is -Pitch*0.3+12,
    pt(Head, SnoutDir, 15, Snout),
    pt(Head, 180, 4, Back),
    capsule([Back, Head, Snout], [9, 9, 4.5], HeadS),
    % ears
    pt(Head, -100, 6, EarBase),
    findall(Ear,
            ( member(K-DA, [0-0, 1-(-14)]),
              BL is 4*K,
              pt(EarBase, 180, BL, EB),
              EA is -110+DA,
              pt(EB, EA, 9, EM),
              pt(EB, EA, 17, Tip),
              capsule([EB, EM, Tip], [4.5, 4, 1.2], Ear)
            ), Ears),
    % thigh and leg
    pt(Hip, AThigh, 9, ThighC),
    ellipse(ThighC, 17, 13, AThigh, Thigh),
    capsule([Knee, Ankle, Toe], [7, 4.5, 3], Leg),
    % near arm
    capsule([Chest, Elbow, Paw], [3.5, 3, 2.5], Arm),
    append([[Tail, Rump, Torso, ChestE, NeckS, HeadS], Ears,
            [Thigh, Leg, Arm]], Near),
    % details: belly, inner ear, eye, nose
    BellyDir is BodyDir-18,
    pt(Hip, BellyDir, 26, BellyC),
    BellyA is BodyDir+10,
    ellipse(BellyC, 22, 11, BellyA, Belly),
    pt(EarBase, -110, 3, IE1), pt(EarBase, -110, 9, IE2),
    pt(EarBase, -110, 14, IE3),
    capsule([IE1, IE2, IE3], [2.2, 2, 0.6], InnerEar),
    EyeDir is -Pitch*0.3-25,
    pt(Head, EyeDir, 4, EyeC),
    ellipse(EyeC, 2.0, 2.4, 0, Eye),
    pt(Snout, 180, 1, NoseC),
    ellipse(NoseC, 2.2, 1.8, 0, Nose),
    Details = [belly-Belly, ear-InnerEar, eye-Eye, nose-Nose],
    % the feet
    figure_scale(S),
    Ankle = _-Y1, Toe = ToeX0-Y2, FT = _-Y3, FA = _-Y4,
    max_list([Y1, Y2, Y3, Y4], LowY),
    Low is LowY*S,
    ToeX is ToeX0*S.

shift(X0-Y0, DX, DY, X-Y) :-
    X is X0+DX,
    Y is Y0+DY.

ellipse(X-Y, RX, RY, A, ellipse(X, Y, RX, RY, A)).

%!  contact_x(-X) is det.
%
%   X of the toe at take-off, relative to the hip.

contact_x(X) :-
    contact(C),
    kangaroo_shapes(C, _, _, _, _, X).

