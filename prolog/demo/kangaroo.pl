/* - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -
This demo illustrates (like the juggler  demo) annimation in  xpce.  A
timer is attached to the drawing area that moves all graphicals in the
window by step/1 points and sets them in the next annimation status.

A kangaroo is a figure holding the frames of a hop as bitmaps.  The
images are SVG documents that are generated by this file and loaded from
a text_buffer.  The kangaroo is drawn from a _pose_: the body pitch and
the directions of thigh, shin, foot, tail and arm.  A hop of frames/1
frames interpolates between the key poses of key_pose/8.  Each frame
shifts the kangaroo inside the image such that, combined with the
constant step, its feet stay on the ground while it crouches and all
forward motion happens in the air.  Each body part is drawn twice:
first with a thick stroke in the outline colour and then filled without
stroke.  This gives a single outline around the silhouette of the whole
body.  The kangaroos come in the colours of palette/6.

Left-click in the drawing area adds a kangaroo to the diagram.
- - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - */

:- module(kangaroo, [ kangaroo/0]).
:- use_module(library(pce)).
:- use_module(library(apply)).
:- use_module(library(lists)).
:- use_module(library(pairs), [pairs_keys_values/3]).

kangaroo :-
    step(Step),
    new(Pict, window('Kangaroo animation demo', size(640, 240))),
    new(Msg, message(Pict?graphicals, for_all,
                     and(message(@arg1, next_status),
                         if(@arg1?right_side > Pict?visible?right_side,
                            message(@arg1, x, 0),
                            message(@arg1, relative_move, point(Step, 0)))))),
    send(Pict, attribute, attribute(timer, new(T, timer(0.1, Msg)))),
    send(T, start),

    send(Pict, recogniser,
         click_gesture(left, '', single,
                       message(@prolog, new_kangaroo,
                               @receiver, @event?position))),

    send(new(D, dialog), below, Pict),
    send(D, append,
         label(help, 'Left-click in the main window for a new kangaroo')),
    send(D, append,
         slider(speed, 0, 10, 2, message(@prolog, set_speed, T, @arg1))),

    send(D, append, button(clear, message(Pict, clear))),
    send(D, append, new(Quit, button(quit, and(message(T, free),
                                               message(D, destroy))))),
    send(D, done_message, message(Quit, execute)),

    new_kangaroo(Pict, point(20,100)),

    send(Pict, open).


set_speed(T, 0) :-
    !,
    send(T, stop).
set_speed(T, N) :-
    Time is 1/(9*N),
    send(T, interval, Time),
    send(T, running, @on).

%!  new_kangaroo(+Pict, +Pos)
%
%   Add a kangaroo at Pos.  Each new kangaroo has the next colour and
%   starts at a random moment of its hop.

new_kangaroo(Pict, Pos) :-
    findall(C, palette(C, _, _, _, _, _), Colours),
    length(Colours, NC),
    flag(kangaroo_colour, I, I+1),
    Nth is I mod NC,
    nth0(Nth, Colours, Colour),
    frames(Frames),
    new(F, figure),
    forall(between(1, Frames, N),
           ( kangaroo_image(Colour, N, Image),
             send(F, display, new(BM, bitmap(Image))),
             send(BM, name, N)
           )),
    random_between(1, Frames, Start),
    send(F, status, Start),
    send(Pict, display, F, Pos).

%!  kangaroo_image(+Colour, +N, -Image) is det.
%
%   Image is frame N (1-based) of a kangaroo in Colour.  The images are
%   generated on first use and shared by all kangaroos of this colour.

:- dynamic
    image_cache/3,                      % Colour, N, Image
    base_x_/1.

kangaroo_image(Colour, N, Image) :-
    image_cache(Colour, N, Image),
    !.
kangaroo_image(Colour, N, Image) :-
    base_x(BaseX),
    I is N-1,
    frame(I, Colour, BaseX, _, SVG),
    new(TB, text_buffer),
    send(TB, insert, 0, SVG),
    pixels(Width),
    new(Image, image(TB, Width)),
    send(Image, lock_object, @on),
    assertz(image_cache(Colour, N, Image)).

base_x(BaseX) :-
    base_x_(BaseX0),
    !,
    BaseX = BaseX0.
base_x(BaseX) :-
    layout(BaseX),
    assertz(base_x_(BaseX)).

