%!  frame(+I, +Palette, +BaseX, -BBox, -SVG) is det.
%
%   SVG is frame I (0-based) in Palette.  BBox is bbox(X0,Y0,X1,Y1) of
%   the body parts, used to centre the hop.

frame(I, Palette, BaseX, BBox, SVG) :-
    palette(Palette, Body, Shade, Belly, Outline, EarC),
    frames(N),
    T is I/N,
    kangaroo_shapes(T, Near, Far, Details, Low, ToeX),
    frame_offset(I, T, Low, ToeX, BaseX, DX, DY),
    figure_scale(S),
    maplist(transform(S, DX, DY), Near, NearT),
    maplist(transform(S, DX, DY), Far, FarT),
    append(FarT, NearT, All),
    bbox(All, BBox),
    stroke_width(SW),
    SW2 is 2*SW,
    canvas(W, H),
    format(string(Head),
           '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ~d ~d" \c
            width="~d" height="~d">',
           [W, H, W, H]),
    maplist(svg_shape_(Shade, stroke(Outline, SW)), FarT, FarE),
    maplist(svg_shape_(Outline, stroke(Outline, SW2)), NearT, OutlineE),
    maplist(svg_shape_(Body, none), NearT, FillE),
    Colours = _{belly:Belly, ear:EarC, eye:Outline, nose:Outline},
    maplist(detail(S, DX, DY, Colours), Details, DetailE),
    append([[Head], FarE, OutlineE, FillE, DetailE, ["</svg>"]], Lines),
    atomic_list_concat(Lines, '\n', SVG0),
    atom_concat(SVG0, '\n', SVG).

svg_shape_(Fill, Stroke, Shape, SVG) :-
    svg_shape(Shape, Fill, Stroke, SVG).

detail(S, DX, DY, Colours, Kind-Shape, SVG) :-
    transform(S, DX, DY, Shape, ShapeT),
    get_dict(Kind, Colours, Colour),
    svg_shape(ShapeT, Colour, none, SVG).

%!  frame_offset(+I, +T, +Low, +ToeX, +BaseX, -DX, -DY) is det.
%
%   Position of the hip in frame I.  Vertically, the feet are on the
%   ground in contact, while in flight the hip moves from its take-off
%   to its landing height along an arc.  Horizontally the toe stays put
%   in contact and we advance a full hop over the flight time.  The
%   demo moves the figure by I steps, which we compensate.

frame_offset(I, T, Low, ToeX, BaseX, DX, DY) :-
    contact(C),
    ground_y(G),
    hop(Hop, UnitStep),
    contact_x(CX),
    (   T =< C
    ->  DY is G - Low,
        World is -ToeX
    ;   F is (T-C)/(1-C),
        kangaroo_shapes(C, _, _, _, LowT, _),
        kangaroo_shapes(0.0, _, _, _, LowL, _),
        jump(J),
        DY is (G-LowT) + ((G-LowL)-(G-LowT))*F - J*sin(pi*F),
        World is -CX + Hop*F
    ),
    DX is BaseX + World - I*UnitStep + CX.

%!  hop(-Hop, -UnitStep) is det.
%
%   UnitStep is the step of the demo in viewBox units and Hop the
%   distance covered by a hop.

hop(Hop, UnitStep) :-
    canvas(W, _),
    pixels(PX),
    step(Step),
    frames(N),
    UnitStep is Step / (PX/W),
    Hop is UnitStep*N.

transform(S, DX, DY, ellipse(CX, CY, RX, RY, A),
          ellipse(TX, TY, TRX, TRY, A)) :-
    !,
    TX is CX*S+DX, TY is CY*S+DY,
    TRX is RX*S, TRY is RY*S.
transform(S, DX, DY, smooth(Poly), smooth(TPoly)) :-
    maplist(transform_point(S, DX, DY), Poly, TPoly).

transform_point(S, DX, DY, X-Y, TX-TY) :-
    TX is X*S+DX,
    TY is Y*S+DY.

bbox(Shapes, bbox(X0, Y0, X1, Y1)) :-
    foldl(shape_points, Shapes, [], Points),
    pairs_keys_values(Points, Xs, Ys),
    min_list(Xs, X0), max_list(Xs, X1),
    min_list(Ys, Y0), max_list(Ys, Y1).

shape_points(ellipse(CX, CY, RX, RY, _), Ps0, Ps) :-
    !,
    R is max(RX, RY),
    X0 is CX-R, Y0 is CY-R, X1 is CX+R, Y1 is CY+R,
    Ps = [X0-Y0, X1-Y1|Ps0].
shape_points(smooth(Poly), Ps0, Ps) :-
    append(Poly, Ps0, Ps).

%!  layout(-BaseX) is det.
%
%   Centre the hop horizontally in the canvas.

layout(BaseX) :-
    hop_bbox(0, bbox(X0, _, X1, _)),
    canvas(W, _H),
    BaseX is (W - (X1-X0))/2 - X0.

hop_bbox(BaseX, bbox(X0, Y0, X1, Y1)) :-
    frames(N),
    Last is N-1,
    findall(BB, ( between(0, Last, I),
                  frame(I, red, BaseX, BB, _)
                ), BBs),
    maplist(arg(1), BBs, X0s), min_list(X0s, X0),
    maplist(arg(2), BBs, Y0s), min_list(Y0s, Y0),
    maplist(arg(3), BBs, X1s), max_list(X1s, X1),
    maplist(arg(4), BBs, Y1s), max_list(Y1s, Y1).
